#!/usr/bin/env python3
# Super+F1: browse keybinds; change a bind's key safely, or open the config at that line.
import os, re, shutil, subprocess

CFG = os.path.expanduser("~/.config/hypr/hyprland.lua")
BAK = CFG + ".keybinds.bak"

def rofi(prompt, options="", extra=()):
    return subprocess.run(["rofi", "-dmenu", "-i", "-p", prompt, *extra],
                          input=options, capture_output=True, text=True).stdout.strip()

def notify(title, body):
    subprocess.run(["notify-send", title, body])

def pretty(expr):
    expr = expr.replace('mainMod .. " + ', "SUPER + ").replace(" .. key", "<number>")
    return expr.replace('" .. "', "").replace('"', "").strip()

NAMES = {"SUPER": "Win", "SHIFT": "Shift", "CTRL": "Ctrl", "ALT": "Alt", "Return": "Enter",
         "Delete": "Del", "Print": "PrtSc", "Escape": "Esc", "space": "Space", "Tab": "Tab",
         "left": "\u2190", "right": "\u2192", "up": "\u2191", "down": "\u2193",
         "mouse:272": "Left drag", "mouse:273": "Right drag",
         "mouse_down": "Scroll down", "mouse_up": "Scroll up", "<number>": "1\u20130",
         "XF86AudioRaiseVolume": "Volume up", "XF86AudioLowerVolume": "Volume down",
         "XF86AudioMute": "Mute key", "XF86AudioMicMute": "Mic mute key",
         "XF86MonBrightnessUp": "Brightness up", "XF86MonBrightnessDown": "Brightness down",
         "XF86AudioNext": "Next track key", "XF86AudioPrev": "Previous track key",
         "XF86AudioPlay": "Play key", "XF86AudioPause": "Pause key"}

def friendly(combo):
    """Display-only names, e.g. 'SUPER + SHIFT + Return' -> 'Win + Shift + Enter'."""
    return " + ".join(NAMES.get(k.strip(), k.strip()) for k in combo.split(" + "))

def errors():
    return subprocess.run(["hyprctl", "configerrors"], capture_output=True, text=True).stdout

lines = open(CFG).read().split("\n")
binds = {}
for i, line in enumerate(lines):
    s = line.strip()
    if s.startswith("hl.bind(") and ", hl.dsp." in s:
        start = line.index("hl.bind(") + len("hl.bind(")
        end = line.index(", hl.dsp.")
        key_expr = line[start:end]
        action = re.sub(r",\s*\{[^}]*\}\s*\)$", ")", line[end + len(", hl.dsp."):].strip()).rstrip(")")
        binds[i] = (key_expr, start, end, action)

rows = [f"{friendly(pretty(k)):<32} {a[:70]}  :{i + 1}" for i, (k, _, _, a) in binds.items()]
pick = rofi("Keys", "\n".join(rows), ["-theme-str", "window { width: 950px; }"])
if not pick:
    raise SystemExit

i = int(pick.rsplit(":", 1)[1]) - 1
key_expr, start, end, action = binds[i]

choice = rofi(f"{friendly(pretty(key_expr))}", "Change key\nOpen in editor")
if choice == "Open in editor":
    if shutil.which("code"):
        subprocess.Popen(["code", "--goto", f"{CFG}:{i + 1}"])
    else:
        subprocess.Popen(["kitty", "-e", "nano", f"+{i + 1}", CFG])
    raise SystemExit
if choice != "Change key":
    raise SystemExit

if "key" in key_expr.replace("mainMod", ""):
    notify("Can't change this one here", "It's generated by a loop. Use 'Open in editor' instead.")
    raise SystemExit

new = rofi("New key (e.g. SUPER + Return)").strip()
if not new:
    raise SystemExit
new = re.sub(r"\s*\+\s*", " + ", new)

taken = [a for j, (k, _, _, a) in binds.items() if j != i and pretty(k).lower() == new.lower()]
if taken:
    if rofi(f"{new} is used by {taken[0][:40]}. Use anyway?", "No\nYes") != "Yes":
        raise SystemExit

if new.upper().startswith("SUPER + "):
    new_expr = 'mainMod .. " + ' + new[len("SUPER + "):] + '"'
elif new.upper() == "SUPER":
    new_expr = "mainMod"
else:
    new_expr = '"' + new + '"'

before = errors()
shutil.copy(CFG, BAK)
lines[i] = lines[i][:start] + new_expr + lines[i][end:]
open(CFG, "w").write("\n".join(lines))
subprocess.run(["hyprctl", "reload"], capture_output=True)

if errors() != before:
    shutil.copy(BAK, CFG)
    subprocess.run(["hyprctl", "reload"], capture_output=True)
    notify("Keybind not changed", f"'{new}' caused a config error, so I restored your config.")
else:
    notify("Keybind changed", f"{action[:50]}\n{friendly(pretty(key_expr))}  →  {friendly(new)}")
